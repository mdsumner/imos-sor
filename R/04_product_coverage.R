# Which IMOS gridded products cover which parts of Australia's maritime
# jurisdiction?
#
# For every gridded satellite/model store in inventory/zarr_inventory.jsonl,
# the share of each EEZ territory (eez_legal) and each Australian Marine Park
# network (amp) that lies inside the store's domain. Computed from the union-lattice
# coverage tables; a union cell counts when its centre is inside the store's
# extent (as cell edges), so the store edge is resolved to one 0.02 degree cell.
# Domain only: says nothing about valid data (cloud, ice, land masks).
#
# Writes boundaries/product_coverage.csv and notes/product_coverage.md.
# usage (from the repo root): Rscript R/04_product_coverage.R
suppressPackageStartupMessages(library(sf))
inv <- lapply(readLines("inventory/zarr_inventory.jsonl"), jsonlite::fromJSON)
inv <- Filter(function(r) !is.null(r$lon_min) && grepl("^(satellite|model)_", r$store), inv)
dom <- do.call(rbind, lapply(inv, function(r) {
  h <- r$lon_step / 2; hy <- (r$lat_max - r$lat_min) / (r$lat_n - 1) / 2
  data.frame(store = sub("\\.zarr$", "", r$store),
             xmin = r$lon_min - h, xmax = r$lon_max + h, ymin = r$lat_min - hy, ymax = r$lat_max + hy,
             step = r$lon_step, start = substr(r$time_start, 1, 10), end = substr(r$time_end, 1, 10))
}))

lat <- read.csv("boundaries/lattice.csv"); u <- lat[lat$grid == "union", ]; res <- 0.02
cell_km2 <- function(nrow, ymax, res) {
  a <- 6378137; f <- 1 / 298.257223563; e2 <- f * (2 - f); e <- sqrt(e2); b <- a * (1 - f)
  g <- function(phi) { s <- sin(phi); s / (1 - e2 * s^2) + atanh(e * s) / e }
  top <- (ymax - (seq_len(nrow) - 1) * res) * pi / 180
  (b^2 / 2) * (g(top) - g(top - res * pi / 180)) * (res * pi / 180) / 1e6
}
rowarea <- cell_km2(u$nrow, u$ymax, res)
xc <- function(col) u$xmin + (col - 0.5) * res
yc <- function(row) u$ymax - (row - 0.5) * res

share <- function(tab, groups, d) {
  ## clip each run to the columns whose centres are inside [xmin, xmax]
  c0 <- ceiling((d$xmin - u$xmin) / res + 0.5); c1 <- floor((d$xmax - u$xmin) / res + 0.5)
  inrow <- yc(tab$row) >= d$ymin & yc(tab$row) <= d$ymax
  a <- pmax(tab$col_start, c0); b <- pmin(tab$col_end, c1)
  n <- ifelse(inrow & b >= a, b - a + 1, 0)
  w <- tab$fraction * rowarea[tab$row]
  inside <- tapply(n * w, groups, sum); total <- tapply((tab$col_end - tab$col_start + 1) * w, groups, sum)
  round(100 * inside / total, 1)
}
eez <- nanoparquet::read_parquet("data/coverage/eez_legal.parquet")
eez_reg <- read_sf("data/boundaries/eez_legal.parquet")$region
amp <- nanoparquet::read_parquet("data/coverage/amp.parquet")
amp_net <- read_sf("data/boundaries/amp.parquet")$NETNAME
g_eez <- factor(eez_reg[eez$region_id], levels = eez_reg)
g_amp <- factor(amp_net[amp$region_id], levels = unique(amp_net))

m_eez <- t(sapply(seq_len(nrow(dom)), function(i) share(eez, g_eez, dom[i, ])))
m_amp <- t(sapply(seq_len(nrow(dom)), function(i) share(amp, g_amp, dom[i, ])))
out <- cbind(dom, as.data.frame(m_eez), setNames(as.data.frame(m_amp), paste0("AMP: ", colnames(m_amp))))
write.csv(out, "boundaries/product_coverage.csv", row.names = FALSE)

## markdown: one row per distinct domain, listing the stores that share it
key <- apply(round(dom[, c("xmin", "xmax", "ymin", "ymax")], 2), 1, paste, collapse = " ")
grp <- split(seq_len(nrow(dom)), factor(key, levels = unique(key)))
fmt <- function(v) ifelse(v == 100, "100", ifelse(v == 0, "**0**", sprintf("%.1f", v)))
hdr <- c("# IMOS gridded products: share (%) of each EEZ territory and AMP network inside the product domain", "",
         "Generated by R/04_product_coverage.R from the union-lattice coverage tables.",
         "EEZ territories are GA AMB2020 (Perth Treaty), 12-200 nm. Domain only: cloud, ice and land masks are not considered.", "",
         "Territories: MLD mainland incl. Tasmania, Lord Howe, Ashmore/Cartier; TST Torres Strait; CI Christmas Is.; CKI Cocos (Keeling);",
         "NI Norfolk; MAC Macquarie; HIMI Heard and McDonald; AATW/AATE Australian Antarctic Territory west/east of Adelie Land.", "")
cols <- c(colnames(m_eez))
tb <- c(paste0("| domain (lon; lat) | step | stores | ", paste(cols, collapse = " | "), " |"),
        paste0("|---|---|---|", paste(rep("---", length(cols)), collapse = "|"), "|"))
for (k in names(grp)) {
  i <- grp[[k]]; d <- dom[i[1], ]
  st <- paste(sprintf("%s (%s..%s)", dom$store[i], substr(dom$start[i], 1, 4), substr(dom$end[i], 1, 4)), collapse = "<br>")
  tb <- c(tb, sprintf("| %.2f..%.2f; %.2f..%.2f | %.4g | %s | %s |", d$xmin, d$xmax, d$ymin, d$ymax, d$step, st,
                      paste(fmt(m_eez[i[1], ]), collapse = " | ")))
}
cols2 <- colnames(m_amp)
tb2 <- c("", "## AMP networks", "",
         paste0("| domain (lon; lat) | ", paste(cols2, collapse = " | "), " |"),
         paste0("|---|", paste(rep("---", length(cols2)), collapse = "|"), "|"))
for (k in names(grp)) {
  i <- grp[[k]]; d <- dom[i[1], ]
  tb2 <- c(tb2, sprintf("| %.2f..%.2f; %.2f..%.2f | %s |", d$xmin, d$xmax, d$ymin, d$ymax, paste(fmt(m_amp[i[1], ]), collapse = " | ")))
}
writeLines(c(hdr, tb, tb2), "notes/product_coverage.md")
print(cbind(store = substr(dom$store, 1, 55), as.data.frame(m_eez))[!duplicated(key), ], row.names = FALSE)
